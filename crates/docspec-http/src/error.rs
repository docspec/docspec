    /// Builds a router with only the request-id layers and
    /// `attach_problem_instance`, the way `router()` composes them.
    fn instance_router() -> axum::Router {
        use axum::http::header::HeaderName;
        use tower_http::request_id::{MakeRequestUuid, PropagateRequestIdLayer, SetRequestIdLayer};

        axum::Router::new()
            .route(
                "/problem",
                axum::routing::get(|| async { Err::<(), HttpError>(HttpError::EmptyBody) }),
            )
            .route("/ok", axum::routing::get(|| async { "fine" }))
            .layer(axum::middleware::from_fn(attach_problem_instance))
            .layer(PropagateRequestIdLayer::new(HeaderName::from_static(
                "x-request-id",
            )))
            .layer(SetRequestIdLayer::new(
                HeaderName::from_static("x-request-id"),
                MakeRequestUuid,
            ))
    }

    async fn send(router: axum::Router, path: &str, request_id: Option<&str>) -> Response {
        use tower::ServiceExt as _;
        let mut builder = axum::http::Request::builder().uri(path);
        if let Some(id) = request_id {
            builder = builder.header("x-request-id", id);
        }
        router
            .oneshot(builder.body(Body::empty()).unwrap())
            .await
            .unwrap()
    }

    #[tokio::test]
    async fn middleware_sets_instance_from_a_uuid_request_id() {
        let response = send(
            instance_router(),
            "/problem",
            Some("0F8FAD5B-D9CB-469F-A165-70867728950E"),
        )
        .await;
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        assert_eq!(
            response.headers().get(CONTENT_TYPE).unwrap(),
            "application/problem+json"
        );
        let content_length = response
            .headers()
            .get(CONTENT_LENGTH)
            .map(|value| value.to_str().unwrap().to_owned());
        let bytes = axum::body::to_bytes(response.into_body(), usize::MAX)
            .await
            .unwrap();
        assert_eq!(
            bytes.as_ref(),
            br#"{"type":"about:blank","title":"Bad Request","status":400,"detail":"Request body is empty","instance":"urn:uuid:0f8fad5b-d9cb-469f-a165-70867728950e"}"#
        );
        // Whatever set Content-Length did so after the body was replaced.
        assert_eq!(content_length, Some(bytes.len().to_string()));
    }

