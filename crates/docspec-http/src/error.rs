/// Base of every problem `type` URI this server defines
/// ([RFC 9457 §4](https://www.rfc-editor.org/rfc/rfc9457#section-4)).
///
/// Each type is a path under this base. The host serves one document with
/// an anchor per type and redirects each path to its anchor; the source of
/// that document is the "Problem types" table in this crate's README.
pub const PROBLEM_TYPE_BASE: &str = "https://problems.docspec.dev/";

/// `type` of a `422` whose document the parser or emitter rejected.
pub const PROBLEM_TYPE_MALFORMED_INPUT: &str = "https://problems.docspec.dev/malformed-input";

/// `type` of a `422` whose document is well-formed but holds something that
/// cannot be converted.
pub const PROBLEM_TYPE_UNSUPPORTED_CONTENT: &str =
    "https://problems.docspec.dev/unsupported-content";

/// Why a document could not be converted; selects the `type` of a `422`.
///
/// Chosen by `docspec_core::Error` kind, never by message text:
///
/// | Variant | Core error kinds | `type` |
/// | --- | --- | --- |
/// | [`Malformed`](Self::Malformed) | `Parse`, `Json` | [`PROBLEM_TYPE_MALFORMED_INPUT`] |
/// | [`Unsupported`](Self::Unsupported) | `Other`, `Io`, any future kind | [`PROBLEM_TYPE_UNSUPPORTED_CONTENT`] |
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum InputProblem {
    /// The parser or emitter rejected the document's structure: a syntax
    /// error, or a document that ends before its structure closes.
    Malformed,
    /// The document is well-formed but holds a dangling reference, a missing
    /// media part, or a value the output format cannot represent.
    Unsupported,
}

impl InputProblem {
    /// The problem `type` URI for this kind of input problem.
    #[inline]
    #[must_use]
    pub const fn type_uri(self) -> &'static str {
        match self {
            Self::Malformed => PROBLEM_TYPE_MALFORMED_INPUT,
            Self::Unsupported => PROBLEM_TYPE_UNSUPPORTED_CONTENT,
        }
    }
}

/// RFC 9457 Problem Details for HTTP APIs.
///
/// Carries four of the members defined in
/// [RFC 9457 §3.1](https://www.rfc-editor.org/rfc/rfc9457#section-3.1):
/// `type`, `title`, `status`, and `detail`, plus `instance` when the request
/// id is known. `type` is `about:blank`
/// ([§4.2.1](https://www.rfc-editor.org/rfc/rfc9457#section-4.2.1)) unless
/// the status alone does not say what went wrong; today only `422` carries a
/// specific type (see [`InputProblem`]).
/// Serialized via [`ProblemJson::to_json_bytes`]; fields are declared in the
/// order they appear in the body.
#[derive(Debug, Clone, Serialize)]
pub struct ProblemJson {
    /// URI reference identifying the problem type
    /// ([RFC 9457 §3.1.1](https://www.rfc-editor.org/rfc/rfc9457#section-3.1.1)).
    ///
    /// `"about:blank"` ([§4.2.1](https://www.rfc-editor.org/rfc/rfc9457#section-4.2.1))
    /// unless the status alone is ambiguous; `422` uses one of the
    /// [`InputProblem`] URIs under [`PROBLEM_TYPE_BASE`].
    #[serde(rename = "type")]
    pub type_uri: &'static str,
    /// Short, human-readable summary of the problem type.
    ///
    /// Matches the HTTP reason phrase for the status code, as
    /// [RFC 9457 §4.2.1](https://www.rfc-editor.org/rfc/rfc9457#section-4.2.1)
    /// recommends for the `about:blank` type. Phrases follow
    /// [RFC 9110 §15](https://www.rfc-editor.org/rfc/rfc9110#section-15), so
    /// `422` is "Unprocessable Content".
    pub title: &'static str,
    /// HTTP status code generated by this occurrence.
    pub status: u16,
    /// Human-readable explanation specific to this occurrence.
    ///
    /// Describes the caller's request or document so they can correct it
    /// ([RFC 9457 §3.1.4](https://www.rfc-editor.org/rfc/rfc9457#section-3.1.4)).
    /// It never carries server implementation details such as file system
    /// paths, stack traces or configuration
    /// ([§5](https://www.rfc-editor.org/rfc/rfc9457#section-5)); internal
    /// failures use a fixed message instead (see [`HttpError::Internal`]).
    /// May contain user-supplied data such as path names or MIME type strings.
    /// Dynamic values are stored as [`Cow::Owned`]; static strings as [`Cow::Borrowed`].
    pub detail: Cow<'static, str>,
    /// URI reference identifying this occurrence
    /// ([RFC 9457 §3.1.5](https://www.rfc-editor.org/rfc/rfc9457#section-3.1.5)).
    ///
    /// `urn:uuid:<request id>` when the router knows the request id and it is
    /// a UUID; set by the router's problem-instance middleware, never by
    /// [`HttpError::into_response`] itself. Omitted from the body when `None`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance: Option<String>,
}

/// `OpenAPI` schema of the body [`ProblemJson::to_json_bytes`] writes.
///
/// A crate-private, schema-only mirror, so the public [`ProblemJson`] does not
/// implement a `utoipa` trait and `utoipa` stays out of this crate's public
/// API. The `problem_body_matches_its_schema` test checks real bodies against it.
pub(crate) enum Problem {}

impl utoipa::PartialSchema for Problem {
    fn schema() -> RefOr<Schema> {
        let string = |description: &str| {
            ObjectBuilder::new()
                .schema_type(Type::String)
                .description(Some(description))
        };
        ObjectBuilder::new()
            .description(Some(
                "RFC 9457 problem details. Switch on `type`, not on `detail`, which is free text. \
                 `type` is `about:blank` when the status says everything, otherwise a URI under \
                 https://problems.docspec.dev/.",
            ))
            .property(
                "detail",
                string("Human-readable explanation specific to this occurrence."),
            )
            .required("detail")
            .property(
                "instance",
                string("`urn:uuid:<request id>` when the request id is known; omitted otherwise."),
            )
            .property(
                "status",
                ObjectBuilder::new()
                    .schema_type(Type::Integer)
                    .minimum(Some(100))
                    .maximum(Some(599))
                    .description(Some("HTTP status code generated by this occurrence.")),
            )
            .required("status")
            .property(
                "title",
                string("Short, human-readable summary of the problem type."),
            )
            .required("title")
            .property(
                "type",
                string("URI reference identifying the problem type."),
            )
            .required("type")
            .into()
    }
}

